PAM_RULE = re.compile(
    r"^(?P<indent>[ \t]*)(?P<type>-?(?:auth|account|password|session))"
    r"[ \t]+(?P<control>\[[^\]]+\]|\w+)[ \t]+(?P<module>\S+)"
    r"(?P<args>[^\n]*)$", re.IGNORECASE,
)


def run(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    print(f"$ {shlex.join(cmd)}", flush=True)
    return subprocess.run(cmd, check=True, text=True, encoding="utf-8")


def pam_content(path: Path, *, passwordless: bool = False) -> str:
    """Normalize keyring hooks while retaining the service's other PAM rules."""
    source = path if path.exists() else PAM_VENDOR / path.name
    text = source.read_text(encoding="utf-8")  # Never create an empty login stack.
    rules: list[str] = []
    options: dict[str, list[str]] = {}
    for line in text.splitlines():
        rule = PAM_RULE.fullmatch(line)
        if rule is None:
            if line.strip() and not line.lstrip().startswith("#"):
                raise ValueError(f"{source}: unsupported PAM rule: {line}")
            rules.append(line)
            continue
        kind = rule["type"].lstrip("-").lower()
        module = Path(rule["module"]).name
        if module == "pam_gnome_keyring.so" and kind in ("auth", "session", "password"):
            # Preserve custom arguments from the first hook of each type.
            options.setdefault(kind, rule["args"].split("#", 1)[0].split())
            continue
        if (module == "pam_systemd_loadkey.so" and kind == "auth"
                and rule["control"].lower() == "optional"
                and not rule["args"].split("#", 1)[0].strip()):
            continue  # Remove the ineffective hook generated by earlier versions.
        control = rule["control"].lower()
        if kind in ("auth", "password", "session"):
            if control == "sufficient" or (
                control.startswith("[") and re.search(r"=\s*(?:done|\d+)\b", control)
            ):
                raise ValueError(f"{source}: custom PAM short-circuit requires manual review: {line}")
            # Keep successful short-circuits inside included stacks so hooks run.
            if not passwordless and control == "include" and kind in ("auth", "password"):
                line = line[:rule.start("control")] + "substack" + line[rule.end("control"):]
        rules.append(line)
    kinds = {m["type"].lstrip("-").lower() for line in rules
             if (m := PAM_RULE.fullmatch(line))}
    if not {"auth", "account", "session"} <= kinds:
        raise ValueError(f"{source}: incomplete PAM stack; refusing to replace it")
    for kind in ("auth", "password", "session"):
        if passwordless and kind != "session":
            continue  # Do not create/update an encrypted login keyring on password login.
        if kind not in kinds:
            continue
        args = options.get(kind, []).copy()
        required = PAM_HOOK_ARGS.get(kind)
        if required and required not in args:
            args.append(required)
        hook = f"{kind:<10} optional     pam_gnome_keyring.so"
        if args:
            hook += " " + " ".join(args)
        indices = [i for i, line in enumerate(rules)
                   if (m := PAM_RULE.fullmatch(line)) and m["type"].lstrip("-").lower() == kind]
        rules.insert(indices[-1] + 1, hook)
    return "\n".join(rules) + "\n"


def filesystem_encrypted(path: Path) -> bool:
    """Check every backing device, including Btrfs subvolumes and LVM/RAID."""
    target = path.resolve()
    while not target.exists():
        target = target.parent
    mount = json.loads(subprocess.check_output(
        ["findmnt", "--json", "--first-only", "--target", str(target),
         "--output", "SOURCES"], text=True, encoding="utf-8",
    ))["filesystems"][0]
    sources = mount["sources"]
    if not sources:
        raise RuntimeError(f"Cannot determine backing filesystem for {path}")

    def encrypted_branch(device: dict) -> bool:
        if device["type"] == "crypt":
            return True
        children = device.get("children", [])
        return bool(children) and all(encrypted_branch(child) for child in children)

    for source in dict.fromkeys(s.split("[", 1)[0] for s in sources):
        # Live ISO overlays, network filesystems and tmpfs are not disk encryption.
        if not source.startswith("/dev/"):
            return False
        devices = json.loads(subprocess.check_output(
            ["lsblk", "--json", "--inverse", "--paths", "--output", "NAME,TYPE", "--", source],
            text=True, encoding="utf-8",
        ))["blockdevices"]
        if not devices:
            raise RuntimeError(f"Cannot determine block topology for {source}")
        if not all(encrypted_branch(device) for device in devices):
            return False
    return True


def resolve_mode(mode: str) -> str:
    if mode in ("unencrypted", "autologin"):
        return "password" if mode == "unencrypted" else "autologin"
    encrypted = filesystem_encrypted(Path("/"))
    print(f"Root filesystem encrypted: {encrypted}")
    if mode in ("luks", "encrypted") and not encrypted:
        raise ValueError("LUKS mode requires an encrypted root filesystem")
    return "luks" if encrypted else "password"


def user_directory(path: Path, user: pwd.struct_passwd, *, mode: int = 0o755) -> None:
    missing = []
    parent = path
    while not parent.exists():
        missing.append(parent)
        parent = parent.parent
    for directory in reversed(missing):
        directory.mkdir()
        os.chown(directory, user.pw_uid, user.pw_gid)
    os.chown(path, user.pw_uid, user.pw_gid)
    path.chmod(mode)


def check_passwordless_keyring(directory: Path) -> None:
    path = directory / f"{KEYRING_NAME}.keyring"
    if not path.exists():
        return
    doc = configparser.ConfigParser(interpolation=None)
    try:
        doc.read_string(path.read_text(encoding="utf-8"))
    except (UnicodeError, configparser.Error) as error:
        raise ValueError(f"{path} is not a readable passwordless keyring; leaving it intact") from error
    if not doc.has_section("keyring"):
        raise ValueError(f"{path} is not a passwordless keyring; leaving it intact")


def setup_passwordless_keyring(directory: Path, user: pwd.struct_passwd, *, dry_run: bool) -> None:
    check_passwordless_keyring(directory)
    keyring = directory / f"{KEYRING_NAME}.keyring"
    default = directory / "default"
    if default.exists() and default.read_text(encoding="utf-8").strip() != KEYRING_NAME:
        print("Selecting Dusky as the default keyring; existing keyrings and their secrets remain intact. "
              "Apps using an old encrypted collection may still request its password.")
    if not dry_run:
        user_directory(directory, user, mode=0o700)
    if not keyring.exists():
        content = ("[keyring]\ndisplay-name=Dusky\n"
                   f"ctime={int(time.time())}\nmtime=0\nlock-on-idle=false\nlock-after=false\n")
        write(keyring, content, mode=0o600, owner=(user.pw_uid, user.pw_gid), dry_run=dry_run)
    elif dry_run:
        print(f"Retain {keyring}; ensure mode 0600 and ownership by {user.pw_name}")
    else:
        # Metadata only: never rewrite existing secrets or print them in a preview.
        os.chown(keyring, user.pw_uid, user.pw_gid)
        keyring.chmod(0o600)
    write(default, f"{KEYRING_NAME}\n", mode=0o600,
          owner=(user.pw_uid, user.pw_gid), dry_run=dry_run)
    print("Passwordless default keyring uses filesystem encryption; no LUKS password transfer is needed.")


def managed_tty_override(path: Path) -> bool:
    if not path.exists():
        return False
    content = path.read_text(encoding="utf-8").rstrip("\n")
    match = re.search(r"--autologin ([a-zA-Z0-9_][a-zA-Z0-9_.-]*) ", content)
    if not match:
        return False
    prefix = f"[Service]\nExecStart=\nExecStart=-/usr/bin/agetty --autologin {match[1]} "
    return content in (
        prefix + "--noclear --noissue %I $TERM",
        prefix + "--noreset --noclear --noissue -- - ${TERM}",
    )


def systemd_active() -> bool:
    try:
        if Path("/proc/1/comm").read_text(encoding="utf-8").strip() != "systemd":
            return False
        process_root = Path("/proc/1/root").stat()
        root = Path("/").stat()
    except OSError:
        # Installer chroots may have no procfs or no access to the host's PID 1.
        return False
    return (process_root.st_dev, process_root.st_ino) == (root.st_dev, root.st_ino)


def backup(path: Path) -> Path:
    dest = path.with_name(f"{path.name}.bak.{time.time_ns()}")
    shutil.copy2(path, dest)
    return dest


def atomic_write(path: Path, content: str, *, mode: int | None = None,
                 owner: tuple[int, int] | None = None) -> None:
    # Follow existing symlinks rather than replacing a site's chosen layout.
    path = path.resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.stat() if path.exists() else None
    fd, name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.tmp.")
    temp = Path(name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
            uid, gid = owner if owner else ((old.st_uid, old.st_gid) if old else (0, 0))
            os.fchown(stream.fileno(), uid, gid)
            os.fchmod(stream.fileno(), mode if mode is not None else
                      (stat.S_IMODE(old.st_mode) if old else 0o644))
            stream.flush()
            os.fsync(stream.fileno())
        if old:
            backup(path)  # A failed backup must prevent replacement.
        os.replace(temp, path)
        directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        temp.unlink(missing_ok=True)
    olds = sorted((p for p in path.parent.glob(f"{path.name}.bak.*")
                   if p.name.rsplit(".", 1)[-1].isdigit()),
                  key=lambda p: int(p.name.rsplit(".", 1)[-1]), reverse=True)
    for old_backup in olds[5:]:
        old_backup.unlink()


def write(path: Path, content: str, *, dry_run: bool, mode: int | None = None,
          owner: tuple[int, int] | None = None) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        info = path.stat()
        if (mode is None or stat.S_IMODE(info.st_mode) == mode) and (
            owner is None or (info.st_uid, info.st_gid) == owner
        ):
            print(f"Unchanged: {path}")
            return
    if dry_run:
        print(f"Would write {path}:\n{content}")
    else:
        atomic_write(path, content, mode=mode, owner=owner)
        if path.read_text(encoding="utf-8") != content:
            raise OSError(f"Readback mismatch: {path}")
        print(f"Updated: {path}")


def target_user(name: str | None) -> pwd.struct_passwd:
    if name is None:
        name = os.environ.get("SUDO_USER")
        if not name and os.getuid() != 0:
            name = pwd.getpwuid(os.getuid()).pw_name
        if not name or name == "root":
            users = [u for u in pwd.getpwall() if 1000 <= u.pw_uid < 60000
                     and u.pw_name not in ("nobody", "greeter")]
            if len(users) != 1:
                raise ValueError("Specify --user when running as root with multiple or no regular users")
            name = users[0].pw_name
    user = pwd.getpwnam(name)
    if user.pw_uid == 0 or not Path(user.pw_dir).is_dir():
        raise ValueError(f"Invalid desktop user/home: {name}")
    return user


def greetd_content(user: str, mode: str) -> str:
    # Preserve terminal/general settings; session commands are managed here.
    doc = tomllib.loads(GREETD_CFG.read_text(encoding="utf-8")) if GREETD_CFG.exists() else {}
    terminal = doc.get("terminal", {})
    if not isinstance(terminal, dict) or not isinstance(doc.get("general", {}), dict):
        raise ValueError("greetd terminal/general settings must be TOML tables")
    # The packaged service conflicts with getty@tty1, so keep its VT aligned.
    terminal["vt"] = 1
    sections = {"terminal": terminal}
    if "general" in doc:
        sections["general"] = doc["general"]
    if sections.get("general", {}).get("service", "greetd") != "greetd":
        raise ValueError("Custom greetd PAM service requires manual review")
    sections["default_session"] = {
        "command": f"tuigreet --time --remember --remember-session --cmd {WAYLAND_SESSION}",
        "user": "greeter",
    }
    if mode in ("luks", "autologin"):
        sections["initial_session"] = {"command": str(WAYLAND_SESSION), "user": user}
    lines = ["# Generated by 127_pam_keyring_greetd.py"]
    for section, values in sections.items():
        lines.extend(("", f"[{section}]"))
        for key, value in values.items():
            if not re.fullmatch(r"[A-Za-z0-9_-]+", key) or type(value) not in (str, int, bool):
                raise ValueError(f"Unsupported greetd setting: {section}.{key}")
            # greetd's configuration parser requires bare keys, even though
            # Python's TOML parser also accepts quoted ones.
            lines.append(f"{key} = {json.dumps(value, ensure_ascii=False)}")
    content = "\n".join(lines) + "\n"
    tomllib.loads(content)
    return content


def install_packages(packages: tuple[str, ...], dry_run: bool) -> None:
    result = subprocess.run(["pacman", "-T", *packages], text=True, encoding="utf-8",
                            capture_output=True)
    if result.returncode not in (0, 127):
        raise RuntimeError(f"pacman dependency query failed: {result.stderr.strip()}")
    missing = result.stdout.splitlines()
    if missing:
        cmd = ["pacman", "-S", "--needed", "--noconfirm", *missing]
        if dry_run:
            print(f"Would run: {shlex.join(cmd)}")
        else:
            run(cmd)


def configure(args: argparse.Namespace) -> None:
    user = None if args.login_only else target_user(args.user)
    if not args.dry_run and os.geteuid() != 0:
        cmd = ["sudo", "--", sys.executable, str(Path(__file__).resolve()), *sys.argv[1:]]
        if user and not args.user:
            cmd.extend(("--user", user.pw_name))
        os.execvp("sudo", cmd)
    if args.dry_run:
        deploy(args, user)
    else:
        # Share 285_tty_autologin.sh's lock across service changes and state writes.
        with LOGIN_LOCK.open("a", encoding="utf-8") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            deploy(args, user)


def deploy(args: argparse.Namespace, user: pwd.struct_passwd | None) -> None:
    mode = resolve_mode(args.mode)
    passwordless = mode == "luks"
    if passwordless and user is None:
        user = target_user(args.user)
    if user:
        print(f"Target: {user.pw_name}; mode: {mode}")
    keyring_dir = None
    if passwordless:
        data_home = Path(args.data_home) if args.data_home else Path(user.pw_dir) / ".local/share"
        keyring_dir = (data_home / "keyrings").resolve()
        if not filesystem_encrypted(keyring_dir):
            raise ValueError(f"{keyring_dir} is not on an encrypted filesystem; "
                             "LUKS autologin needs encrypted keyring storage")
        check_passwordless_keyring(keyring_dir)
    if mode == "autologin" and not args.login_only:
        print("Autologin skips authentication; a password-protected keyring remains locked.")
        if not args.yes and not args.dry_run:
            if input(f"Enable autologin for {user.pw_name}? [y/N] ").strip().lower() not in ("y", "yes"):
                return

    # Preflight login before package installation or any configuration changes.
    login = pam_content(PAM_LOGIN, passwordless=passwordless)
    greetd = None if args.login_only else greetd_content(user.pw_name, mode)
    greetd_pam = None
    if not args.login_only and (PAM_GREETD.exists() or (PAM_VENDOR / PAM_GREETD.name).exists()):
        greetd_pam = pam_content(PAM_GREETD, passwordless=passwordless)
    packages = ("gnome-keyring", "libsecret", "seahorse") if args.login_only else SYSTEM_PKGS
    install_packages(packages, args.dry_run)
    if args.login_only:
        if not args.dry_run and not PAM_MODULE.is_file():
            raise RuntimeError("GNOME Keyring PAM module is missing")
        if passwordless:
            setup_passwordless_keyring(keyring_dir, user, dry_run=args.dry_run)
        write(PAM_LOGIN, login, dry_run=args.dry_run)
        print("Dry run complete." if args.dry_run else
              "Login PAM verified; re-login to initialize the configured keyring.")
        return

    if greetd_pam is None:
        if args.dry_run:
            print("greetd PAM preview requires the greetd package; no files will be created.")
        else:
            greetd_pam = pam_content(PAM_GREETD, passwordless=passwordless)
    if not args.dry_run:
        for command in ("greetd", "tuigreet", "start-hyprland", "Hyprland",
                        "gnome-keyring-daemon", "secret-tool", "udiskie", "systemctl"):
            if not shutil.which(command):
                raise RuntimeError(f"Required command is missing after package installation: {command}")
        if not PAM_MODULE.is_file():
            raise RuntimeError("GNOME Keyring PAM module is missing")
        greeter = pwd.getpwnam("greeter")
    if passwordless:
        setup_passwordless_keyring(keyring_dir, user, dry_run=args.dry_run)
    write(WAYLAND_SESSION, SESSION_CONTENT, mode=0o755, dry_run=args.dry_run)
    write(PAM_LOGIN, login, dry_run=args.dry_run)
    if greetd_pam is not None:
        write(PAM_GREETD, greetd_pam, dry_run=args.dry_run)
    write(GREETD_CFG, greetd, mode=0o644, owner=(0, 0), dry_run=args.dry_run)

    if args.dry_run:
        print(f"Would create {TUIGREET_CACHE} owned by greeter with mode 0755")
    else:
        TUIGREET_CACHE.mkdir(parents=True, exist_ok=True)
        os.chown(TUIGREET_CACHE, greeter.pw_uid, greeter.pw_gid)
        TUIGREET_CACHE.chmod(0o755)
    # Remove only the exact obsolete drop-in generated by earlier versions.
    if OVERRIDE_CONF.exists() and OVERRIDE_CONF.read_text(encoding="utf-8") == "[Service]\nKeyringMode=inherit\n":
        print(f"Remove obsolete drop-in: {OVERRIDE_CONF}")
        if not args.dry_run:
            backup(OVERRIDE_CONF)
            OVERRIDE_CONF.unlink()
    if args.dry_run:
        print(f"Would mask globally: {' '.join(KEYRING_UNITS)}")
    else:
        run(["systemctl", "--root=/", "--global", "mask", *KEYRING_UNITS])
        for unit in KEYRING_UNITS:
            if (USER_UNITS / unit).resolve() != Path("/dev/null"):
                raise RuntimeError(f"Global mask missing: {unit}")

    cfg_home = Path(args.config_home) if args.config_home else Path(user.pw_dir) / ".config"
    cfg = cfg_home / "udiskie/config.yml"
    if cfg.exists() or cfg.with_suffix(".json").exists():
        print(f"Retaining existing udiskie configuration in {cfg.parent}")
    else:
        if not args.dry_run:
            user_directory(cfg.parent, user)
        write(cfg, UDISKIE_CONTENT, owner=(user.pw_uid, user.pw_gid), dry_run=args.dry_run)

    override = TTY_OVERRIDE
    if managed_tty_override(override):
        print(f"Remove conflicting TTY1 autologin override: {override}")
        if not args.dry_run:
            backup(override)
            override.unlink()
    elif override.exists():
        print(f"Retaining custom TTY1 override: {override} (greetd conflicts with getty@tty1)")
    # 285_tty_autologin.sh uses this fixed path, independently of XDG_CONFIG_HOME.
    state = Path(user.pw_dir) / ".config/dusky/settings/auto_login_tty"
    if args.dry_run:
        write(state, "false\n", owner=(user.pw_uid, user.pw_gid), dry_run=True)
        print("Would enable greetd.service and verify its display-manager alias. Dry run complete.")
        return
    # Enable without restarting the active login manager; works offline in chroots.
    run(["systemctl", "--root=/", "--no-reload", "enable", "--force", "greetd.service"])
    if (not DISPLAY_MANAGER.is_symlink() or not DISPLAY_MANAGER.exists()
            or DISPLAY_MANAGER.resolve().name != "greetd.service"):
        raise RuntimeError("greetd display-manager alias was not installed")
    user_directory(state.parent, user)
    write(state, "false\n", owner=(user.pw_uid, user.pw_gid), dry_run=False)
    if systemd_active():
        run(["systemctl", "daemon-reload"])
    else:
        print("Offline environment: configuration will take effect on boot.")
    if tomllib.loads(GREETD_CFG.read_text(encoding="utf-8")) != tomllib.loads(greetd):
        raise RuntimeError("greetd configuration readback mismatch")
    for path in (PAM_LOGIN, PAM_GREETD):
        if pam_content(path, passwordless=passwordless) != path.read_text(encoding="utf-8"):
            raise RuntimeError(f"PAM verification failed: {path}")
    if passwordless:
        print("Configuration verified: encrypted root → greetd autologin → passwordless Dusky keyring. "
              "Reboot to exercise the full login path.")
    else:
        print("Configuration verified. Re-login/reboot to test keyring unlock; "
              "a password-protected login keyring needs the login password.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Configure GNOME Keyring and native Hyprland/greetd login")
    parser.add_argument("-m", "--mode", default="auto",
                        choices=("auto", "unencrypted", "luks", "encrypted", "autologin"),
                        help="auto: LUKS autologin or password login; luks/encrypted: autologin with "
                             "a passwordless keyring; unencrypted: password login; "
                             "autologin: skip login without changing keyring policy")
    parser.add_argument("--login-only", action="store_true", help="Configure console login PAM and keyring policy")
    parser.add_argument("--user", help="Desktop user (defaults to invoking user or sole regular user)")
    parser.add_argument("--config-home", help="Absolute target user's XDG configuration directory")
    parser.add_argument("--data-home", help="Absolute target user's XDG data directory")
    parser.add_argument("--dry-run", action="store_true", help="Preview without elevation or writes")
    parser.add_argument("--yes", action="store_true", help="Accept explicit autologin")
    parser.add_argument("--verbose", action="store_true", help="Show a traceback on failure")
    args = parser.parse_args()
    env_user = (os.environ.get("SUDO_USER") if os.getuid() == 0
                else pwd.getpwuid(os.getuid()).pw_name)
    # Carry the invoking user's XDG paths through sudo explicitly.
    for name, variable in (("config_home", "XDG_CONFIG_HOME"), ("data_home", "XDG_DATA_HOME")):
        if (getattr(args, name) is None and env_user and env_user != "root"
                and (args.user is None or args.user == env_user)):
            setattr(args, name, os.environ.get(variable) or None)
        value = getattr(args, name)
        option = "--" + name.replace("_", "-")
        if value and not Path(value).is_absolute():
            parser.error(f"{option} must be absolute")
        if value and option not in sys.argv and not any(arg.startswith(f"{option}=") for arg in sys.argv):
            sys.argv.extend((option, value))
    try:
        configure(args)
    except KeyboardInterrupt:
        print("Interrupted; completed changes and backups remain.", file=sys.stderr)
        return 130
    except (OSError, ValueError, KeyError, RuntimeError, EOFError, subprocess.CalledProcessError) as error:
        if args.verbose:
            raise
        print(f"ERROR: {error}", file=sys.stderr)
        print("Dry run failed; no changes made." if args.dry_run else
              "Setup incomplete; completed changes retain backups beside their targets.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
