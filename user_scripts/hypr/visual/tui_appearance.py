# Style presets reset the complete visual domain, so switching order cannot leak
# a previous variant's tuning. Hardware, capture, cursor and interaction choices
# stay as configured. Smooth Blur and factory Reset to Defaults retain their
# original complete-snapshot behavior.
_APPEARANCE_PRESET_DEFAULTS = {
    item.uid: item.default
    for items in SCHEMA.values()
    for item in items
    if (
        item.scope.startswith(("decoration", "group", "workspace_rule/", "window_rule/"))
        or (item.scope == "general" and (
            item.key in {"border_size", "gaps_in", "gaps_out", "float_gaps", "gaps_workspaces"}
            or item.key.startswith("col.")
        ))
    ) and item.uid not in {"group/groupbar.middle_click_close", "group/groupbar.scrolling"}
}
for _preset in SCHEMA[0]:
    if _preset.preset_partial:
        _preset.preset_payload = _APPEARANCE_PRESET_DEFAULTS | _preset.preset_payload

